CREATE VIEW V_DASH_STATUS (STATUS, QTD, VALOR) AS
  SELECT STATUS, COUNT(*), COALESCE(SUM(VL_TOTAL), 0)
    FROM VENDA
   WHERE STATUS > 1
   GROUP BY STATUS;

CREATE VIEW V_VENDAS_MES (ANO, MES, STATUS, QTD, VALOR) AS
  SELECT EXTRACT(YEAR FROM DT_EMISSAO), EXTRACT(MONTH FROM DT_EMISSAO),
         STATUS, COUNT(*), COALESCE(SUM(VL_TOTAL), 0)
    FROM VENDA
   WHERE STATUS IN (2, 3)
   GROUP BY EXTRACT(YEAR FROM DT_EMISSAO), EXTRACT(MONTH FROM DT_EMISSAO), STATUS;

CREATE VIEW V_RANKING_PRODUTO (PRODUTO_ID, DESCRICAO, QTD_VENDIDA, VALOR) AS
  SELECT P.ID, P.DESCRICAO, SUM(I.QUANTIDADE), SUM(I.VL_TOTAL)
    FROM VENDA_ITEM I
    JOIN VENDA V   ON V.ID = I.VENDA_ID AND V.STATUS = 3
    JOIN PRODUTO P ON P.ID = I.PRODUTO_ID
   GROUP BY P.ID, P.DESCRICAO;

CREATE VIEW V_RANKING_CLIENTE (CLIENTE_ID, NOME, QTD_VENDAS, VALOR) AS
  SELECT C.ID, C.NOME, COUNT(*), SUM(V.VL_ITENS - V.VL_DESCONTO)
    FROM VENDA V
    JOIN CLIENTE C ON C.ID = V.CLIENTE_ID
   WHERE V.STATUS = 3
   GROUP BY C.ID, C.NOME;

