CREATE TRIGGER TRG_ITEM_TOTAIS FOR VENDA_ITEM
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE V_VENDA BIGINT;
BEGIN
  V_VENDA = COALESCE(NEW.VENDA_ID, OLD.VENDA_ID);
  UPDATE VENDA
     SET VL_ITENS = (SELECT COALESCE(SUM(I.VL_TOTAL), 0)
                       FROM VENDA_ITEM I
                      WHERE I.VENDA_ID = :V_VENDA)
   WHERE ID = :V_VENDA;
END^

CREATE TRIGGER TRG_ITEM_GUARDA FOR VENDA_ITEM
ACTIVE BEFORE INSERT OR UPDATE OR DELETE POSITION 0
AS
  DECLARE VARIABLE V_STATUS SMALLINT;
BEGIN
  SELECT STATUS FROM VENDA
   WHERE ID = COALESCE(NEW.VENDA_ID, OLD.VENDA_ID)
    INTO :V_STATUS;
  IF (V_STATUS <> 1) THEN
    EXCEPTION E_VENDA_NAO_EDITAVEL;
END^

CREATE TRIGGER TRG_VENDA_TRANSICAO FOR VENDA
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
  IF (OLD.STATUS <> NEW.STATUS) THEN
  BEGIN
    IF (NOT ((OLD.STATUS = 1 AND NEW.STATUS IN (2, 4)) OR
             (OLD.STATUS = 2 AND NEW.STATUS IN (3, 4)))) THEN
      EXCEPTION E_TRANSICAO_INVALIDA;
    IF (NEW.STATUS = 2) THEN
    BEGIN
      IF (NOT EXISTS (SELECT 1 FROM VENDA_ITEM WHERE VENDA_ID = NEW.ID)) THEN
        EXCEPTION E_VENDA_SEM_ITENS;
      NEW.DT_CONFIRMACAO = CURRENT_TIMESTAMP;
    END
    IF (NEW.STATUS = 4) THEN
      NEW.DT_CANCELAMENTO = CURRENT_TIMESTAMP;
  END
  ELSE IF (OLD.STATUS <> 1 AND
           (OLD.CLIENTE_ID <> NEW.CLIENTE_ID OR OLD.VL_DESCONTO <> NEW.VL_DESCONTO)) THEN
    EXCEPTION E_VENDA_NAO_EDITAVEL;
END^

CREATE TRIGGER TRG_VENDA_EXCLUSAO FOR VENDA
ACTIVE BEFORE DELETE POSITION 0
AS
BEGIN
  IF (OLD.STATUS <> 1) THEN
    EXCEPTION E_VENDA_NAO_EDITAVEL;
END^

CREATE TRIGGER TRG_VENDA_QUITADA FOR VENDA
ACTIVE AFTER UPDATE POSITION 10
AS
BEGIN
  IF (OLD.STATUS = 2 AND NEW.STATUS = 3) THEN
  BEGIN
    INSERT INTO EMAIL_OUTBOX (VENDA_ID, EVENTO) VALUES (NEW.ID, 'VENDA_QUITADA');
    POST_EVENT 'VENDA_QUITADA';
  END
END^

